// Export a brand's tokens in formats other tools read.
// DTCG is the W3C design tokens format (Tokens Studio, Style Dictionary, Figma plugins).
import { tokenNames, toCssVars, type TokenName } from './tokens.ts';

type Tokens = Record<TokenName, string>;

const fontStack = (stack: string) => stack.split(',').map((f) => f.trim().replace(/^['"]|['"]$/g, ''));

// "2px" -> { value: 2, unit: "px" }. A fluid clamp() exports its largest size, with the CSS kept alongside.
function dimension(css: string) {
  const parts = [...css.matchAll(/(-?[\d.]+)(px|rem)/g)];
  const last = parts.at(-1);
  const value = last ? { value: Number(last[1]), unit: last[2] } : { value: 0, unit: 'px' };
  const token: Record<string, unknown> = { $type: 'dimension', $value: value };
  if (css.startsWith('clamp(')) token.$extensions = { 'conversion-system': { css } };
  return token;
}

export function toDtcg(id: string, name: string, tokens: Tokens) {
  const color: Record<string, unknown> = {};
  const size: Record<string, unknown> = {};
  const space: Record<string, unknown> = {};
  for (const t of tokenNames) {
    const v = tokens[t];
    if (t.startsWith('color-')) color[t.slice(6)] = { $type: 'color', $value: v };
    else if (t.startsWith('size-')) size[t.slice(5)] = dimension(v);
    else if (t.startsWith('space-')) space[t.slice(6)] = dimension(v);
  }
  return {
    $description: `${name} design tokens, from the conversion system brand "${id}".`,
    color,
    fontFamily: {
      display: { $type: 'fontFamily', $value: fontStack(tokens['font-display']) },
      body: { $type: 'fontFamily', $value: fontStack(tokens['font-body']) },
    },
    fontWeight: { display: { $type: 'fontWeight', $value: Number(tokens['weight-display']) } },
    size,
    space,
    radius: { base: dimension(tokens.radius) },
    measure: { content: dimension(tokens.measure) },
  };
}

export function toCss(name: string, tokens: Tokens): string {
  return `/* ${name} design tokens, generated by the conversion system. */\n:root {\n  ${toCssVars(tokens).split('; ').join(';\n  ')}\n}\n`;
}
